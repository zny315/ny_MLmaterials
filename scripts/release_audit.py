def release_paths() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=ROOT,
        check=True,
        capture_output=True,
    )
    return [
        ROOT / item.decode("utf-8", errors="surrogateescape")
        for item in result.stdout.split(b"\0")
        if item
    ]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def is_public_text(path: Path) -> bool:
    item = relative(path)
    return any(item == prefix or item.startswith(prefix) for prefix in PUBLIC_TEXT_PATHS)


def check_xlsx(path: Path, metadata: dict, errors: list[str]) -> None:
    label = relative(path)
    try:
        with zipfile.ZipFile(path) as archive:
            xml_text = ""
            for name in archive.namelist():
                if name.lower().endswith((".xml", ".rels")):
                    xml_text += archive.read(name).decode("utf-8", errors="ignore")
            if MACHINE_PATH.search(xml_text):
                errors.append(f"machine-specific path in workbook: {label}")
            if HAN.search(xml_text):
                errors.append(f"Han text in workbook: {label}")
            if EMOJI.search(xml_text):
                errors.append(f"emoji in workbook: {label}")
    except zipfile.BadZipFile:
        errors.append(f"invalid XLSX package: {label}")
        return

    workbook = load_workbook(path, read_only=True, data_only=True)
    try:
        sheet = workbook.active
        rows = list(sheet.iter_rows(values_only=True))
        if not rows:
            errors.append(f"empty workbook: {label}")
            return
        headers = ["" if value is None else str(value) for value in rows[0]]
        while headers and not headers[-1].strip():
            headers.pop()
        observed_rows = sum(
            any(value is not None and str(value).strip() for value in row)
            for row in rows[1:]
        )
        if observed_rows != metadata.get("rows"):
            errors.append(f"row-count mismatch: {label}")
        if headers != metadata.get("columns"):
            errors.append(f"column-order mismatch: {label}")
    finally:
        workbook.close()


def audit_manifest(directory: Path, errors: list[str]) -> dict:
    manifest_path = directory / "release_manifest.json"
    if not manifest_path.is_file():
        errors.append(f"missing manifest: {relative(manifest_path)}")
        return {}
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for filename, metadata in manifest.get("files", {}).items():
        path = directory / filename
        if not path.is_file():
            errors.append(f"manifest file missing: {relative(path)}")
            continue
        if sha256(path) != metadata.get("sha256"):
            errors.append(f"manifest hash mismatch: {relative(path)}")
        if path.suffix.lower() == ".xlsx":
            check_xlsx(path, metadata, errors)
    return manifest


def audit_gt50_manifests(errors: list[str]) -> None:
    for path in sorted(GT50.rglob("release_manifest.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        for filename, metadata in payload.get("files", {}).items():
            artifact = path.parent / filename
            if not artifact.is_file():
                errors.append(f"GT50 manifest file missing: {relative(artifact)}")
                continue
            if metadata.get("sha256") and sha256(artifact) != metadata["sha256"]:
                errors.append(f"GT50 manifest hash mismatch: {relative(artifact)}")


def audit() -> list[str]:
    errors: list[str] = []
    paths = release_paths()
    relative_paths = {
        relative(path) for path in paths if path.exists() and path.is_file()
    }

    for required in sorted(REQUIRED_FILES - relative_paths):
        errors.append(f"required file missing: {required}")

    for item in sorted(relative_paths):
        if item in FORBIDDEN_EXACT or item.startswith(FORBIDDEN_PREFIXES):
            errors.append(f"forbidden extraction artifact: {item}")
        if item.lower().endswith(".pdf"):
            errors.append(f"PDF must not be tracked: {item}")
        lower = item.lower()
        if "api_raw" in lower or "raw_responses" in lower or "response_cache" in lower:
            errors.append(f"runtime response artifact must not be tracked: {item}")
        if item.endswith(".json") and item not in ALLOWED_JSON and not item.startswith("firefusion/"):
            errors.append(f"unapproved extraction JSON artifact: {item}")

    for path in paths:
        if not path.exists() or not path.is_file():
            continue
        item = relative(path)
        size = path.stat().st_size
        if size > MAX_TRACKED_BYTES:
            errors.append(f"oversized file ({size / 1024 / 1024:.1f} MiB): {item}")
        lower_parts = {part.lower() for part in path.parts}
        if (
            item != ".env.example"
            and (
                ".secrets" in lower_parts
                or "apikeys" in lower_parts
                or path.name.lower() in {".env", "id_rsa", "id_ed25519"}
                or path.suffix.lower() in {".pem", ".p12", ".pfx"}
            )
        ):
            errors.append(f"sensitive filename/path: {item}")
        if not is_public_text(path) or path.suffix.lower() not in TEXT_SUFFIXES or size > 2 * 1024 * 1024:
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for label, pattern in SECRET_PATTERNS.items():
            if pattern.search(text):
                errors.append(f"possible {label} in {item}")
        if MACHINE_PATH.search(text):
            errors.append(f"machine-specific absolute path in {item}")
        if HAN.search(text):
            errors.append(f"Han text in public extraction text: {item}")
        if EMOJI.search(text):
            errors.append(f"emoji in public extraction text: {item}")
        if ASSISTANT_TRACE.search(text):
            errors.append(f"assistant-style generation trace in public extraction text: {item}")

    literature_manifest = audit_manifest(LITERATURE, errors)
    if set(literature_manifest.get("files", {})) != set(CANONICAL_TABLES):
        errors.append("literature manifest must list exactly four canonical tables")
    audit_gt50_manifests(errors)
    expected = json.loads((GT50 / "expected_metrics.json").read_text(encoding="utf-8"))
    if len(expected.get("metrics", [])) != 16:
        errors.append("GT50 expected metrics must contain 16 method/view rows")
    return errors


def main() -> int:
    try:
        errors = audit()
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError, KeyError) as exc:
        print(f"release audit could not run: {exc}", file=sys.stderr)
        return 2
    if errors:
        print("release audit: FAIL", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    print("release audit: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
